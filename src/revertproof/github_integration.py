"""Real GitHub Integration: Repository verification, PR migration detection,
Commit Status checks, PR Markdown reports, and Webhook HMAC-SHA256 validation.

Uses real GitHub REST API v3 over HTTPS via `httpx`. Never simulates GitHub calls.
"""

from __future__ import annotations

import hashlib
import hmac
import os
import subprocess
from pathlib import Path
from typing import Any

import httpx

from revertproof.models import EvidenceReport, GateDecision

GITHUB_API_BASE = "https://api.github.com"


def verify_github_webhook_signature(
    payload_body: bytes,
    signature_header: str | None,
    webhook_secret: str,
) -> bool:
    """Verify GitHub `X-Hub-Signature-256` using constant-time HMAC-SHA256 comparison."""
    if not signature_header or not webhook_secret:
        return False
    if not signature_header.startswith("sha256="):
        return False
    expected = "sha256=" + hmac.new(
        webhook_secret.encode("utf-8"), payload_body, hashlib.sha256
    ).hexdigest()
    return hmac.compare_digest(expected, signature_header)


def detect_local_git_migrations(
    repo_root: Path,
    base_ref: str = "HEAD~1",
    migration_dirs: list[str] | None = None,
) -> list[str]:
    """Detect added or modified `.sql` migration files using real `git diff`."""
    dirs = [d.strip("/") for d in (migration_dirs or ["migrations", "sql"])]
    try:
        out = subprocess.check_output(
            ["git", "diff", "--name-only", "--diff-filter=AM", f"{base_ref}...HEAD"],
            cwd=str(repo_root),
            stderr=subprocess.DEVNULL,
            text=True,
        )
    except Exception:
        return []

    found: list[str] = []
    for line in out.splitlines():
        rel = line.strip()
        if not rel.lower().endswith(".sql"):
            continue
        if any(rel == d or rel.startswith(d + "/") for d in dirs):
            found.append(rel)
    return sorted(found)


def format_pr_comment_markdown(report: EvidenceReport) -> str:
    """Render a clear GitHub PR review comment with evidence and rollback status."""
    icon = "✅" if report.decision == GateDecision.PASS else "🚫"
    lines = [
        f"## {icon} RevertProof — Deployment Rollback Safety Gate: **{report.decision.value}**",
        "",
        f"- **Run ID:** `{report.run_id}`",
        f"- **Project / Domain:** `{report.domain}`",
        f"- **Migration:** `{report.migration_file}`",
        f"- **Database Engine:** `{report.engine}` | **Records Checked:** `{report.fixture_count}`",
        f"- **Rollback Classification:** `{report.rollback_classification.value}`",
        f"- **Reason:** {report.reason}",
        "",
        "| Check | Result |",
        "|---|---|",
    ]
    for check_name, check_val in report.checks.items():
        lines.append(f"| `{check_name}` | **{check_val}** |")

    if report.scan_report.findings:
        lines.append("")
        lines.append("### Static Scanner Findings")
        for f in report.scan_report.findings:
            lines.append(
                f"- **[{f.severity.value}] `{f.rule_id}`** (line {f.line_number}): {f.explanation}"
            )

    lines.append("")
    lines.append(
        "> *Don't just deploy safely. Prove you can recover safely.* — Generated by **RevertProof**"
    )
    return "\n".join(lines)


class GitHubClient:
    """Real GitHub REST API v3 client for repository verification and PR gating."""

    def __init__(self, token: str | None = None, api_base: str = GITHUB_API_BASE) -> None:
        self.token = token or os.getenv("GITHUB_TOKEN") or os.getenv("RP_GITHUB_TOKEN") or ""
        self.api_base = api_base.rstrip("/")

    def _headers(self) -> dict[str, str]:
        headers = {
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "RevertProof-SafetyGate/1.0",
        }
        if self.token:
            headers["Authorization"] = f"Bearer {self.token}"
        return headers

    def verify_repository(self, repo_full_name: str) -> dict[str, Any]:
        """Verify repository exists and is accessible via GitHub API."""
        url = f"{self.api_base}/repos/{repo_full_name}"
        with httpx.Client(timeout=15.0) as client:
            resp = client.get(url, headers=self._headers())
            resp.raise_for_status()
            data = resp.json()
            return {
                "full_name": data["full_name"],
                "default_branch": data.get("default_branch", "main"),
                "private": bool(data.get("private", False)),
                "html_url": data.get("html_url", f"https://github.com/{repo_full_name}"),
            }

    def list_pr_migration_files(
        self,
        repo_full_name: str,
        pr_number: int,
        migration_dirs: list[str] | None = None,
    ) -> list[dict[str, Any]]:
        """List `.sql` migration files changed in a GitHub Pull Request."""
        dirs = [d.strip("/") for d in (migration_dirs or ["migrations", "sql"])]
        url = f"{self.api_base}/repos/{repo_full_name}/pulls/{pr_number}/files"
        with httpx.Client(timeout=15.0) as client:
            resp = client.get(url, headers=self._headers(), params={"per_page": 100})
            resp.raise_for_status()
            files = resp.json()

        matched: list[dict[str, Any]] = []
        for f in files:
            fname = str(f.get("filename", ""))
            if not fname.lower().endswith(".sql"):
                continue
            if any(fname == d or fname.startswith(d + "/") for d in dirs):
                matched.append(
                    {
                        "filename": fname,
                        "status": f.get("status", "modified"),
                        "raw_url": f.get("raw_url"),
                        "additions": f.get("additions", 0),
                        "deletions": f.get("deletions", 0),
                    }
                )
        return matched

    def publish_commit_status(
        self,
        repo_full_name: str,
        sha: str,
        report: EvidenceReport,
        target_url: str | None = None,
    ) -> dict[str, Any]:
        """Publish a real GitHub Commit Status check to block or allow PR merge."""
        if not self.token:
            raise RuntimeError("GITHUB_TOKEN is required to publish commit status checks.")
        state = "success" if report.decision == GateDecision.PASS else "failure"
        payload: dict[str, Any] = {
            "state": state,
            "context": "RevertProof / Rollback Safety Gate",
            "description": report.reason[:140],
        }
        if target_url:
            payload["target_url"] = target_url

        url = f"{self.api_base}/repos/{repo_full_name}/statuses/{sha}"
        with httpx.Client(timeout=15.0) as client:
            resp = client.post(url, headers=self._headers(), json=payload)
            resp.raise_for_status()
            return resp.json()

    def publish_pr_comment(
        self,
        repo_full_name: str,
        pr_number: int,
        report: EvidenceReport,
    ) -> dict[str, Any]:
        """Post a detailed Markdown evidence report comment on the Pull Request."""
        if not self.token:
            raise RuntimeError("GITHUB_TOKEN is required to post PR comments.")
        body = format_pr_comment_markdown(report)
        url = f"{self.api_base}/repos/{repo_full_name}/issues/{pr_number}/comments"
        with httpx.Client(timeout=15.0) as client:
            resp = client.post(url, headers=self._headers(), json={"body": body})
            resp.raise_for_status()
            return resp.json()
